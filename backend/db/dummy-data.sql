-- 실행 방법
--   bootRun 이 Flyway 로 스키마를 만든 뒤, mysql 컨테이너에 붙어서 실행한다.
--     mysql -u ubidict -p ubidict < backend/db/dummy-data.sql
--
-- 주의 1. 맨 앞 DELETE 블록이 아래 28개 테이블을 전부 비운다. 여러 번 실행해도
--         같은 결과가 되도록 넣은 것이라, 로컬 DB에 남겨 둘 데이터가 있으면
--         실행하지 말 것. 운영·공용 DB에서는 절대 실행 금지.
--
-- 주의 2. member.email / member.display_name 은 MemberFieldEncryptor 가
--         AES-256-GCM 으로 암호화해 저장하는 컬럼이라 평문을 넣으면 조회 시
--         복호화가 깨진다. 아래 값은 application.yml 의 로컬 기본 키
--           app.member.encryption-key = local-dev-only-member-encryption-key-0123456789
--         로 미리 암호화해 둔 암호문이다. MEMBER_ENCRYPTION_KEY 를 다른 값으로
--         덮어썼다면 member INSERT 는 그 키로 다시 만들어야 한다.
--         (결정적 암호화라 같은 평문은 항상 같은 암호문이 된다. 그래서
--          uk_member_email 유니크 제약과 existsByEmail 같은 동등 비교 조회가
--          암호화 이후에도 그대로 동작한다.)
--
-- 주의 3. 시각은 전부 UTC 다. hibernate.jdbc.time_zone=UTC 설정과 맞춘 값이다.
--
-- 주의 4. dictionary.active_flag 는 generated column 이라 INSERT 하지 않는다.
--
-- -----------------------------------------------------------------------------
-- 데이터 구성
-- -----------------------------------------------------------------------------
--   회원 8명 (활성 7 / 탈퇴 1), 워크스페이스 2개
--
--   워크스페이스 1 "러브버그 팀" (문서 리뷰어 2명 / 사전 리뷰어 1명 필요)
--     문서 5개(1개 소프트 삭제) · 문서 버전 9개 · 라벨 4개
--     사전집 v1(ARCHIVED) -> v2(ACTIVE) · 용어 11개
--     문서 초안 5개 (REVISED / EXAMINED / REVIEW_REQUESTED / EXAMINING)
--     사전 초안 4개 · 후보 용어 15개 (승인·동의어병합·거절·보류·유지·대기)
--       └ 표기 그룹(variant_form) 24건. 대표 표기를 포함한 같은 개념의 표기 묶음이다
--     리뷰 요청 5개 (REVISED / IN_REVIEW+재검토1회 / REVISED / PENDING_REVIEW / CANCELED)
--     알림 25건 · 개정 이력 13건
--
--   워크스페이스 2 "사이드 스터디"
--     문서 1개 · 사전집 v1(ACTIVE) · 용어 2개 · 사전 초안 1개
--
--   확인해 볼 만한 경계 사례
--     - document 4 는 사전집 v1 로 대조돼 활성 v2 대비 outdated 다
--     - document 5 / member 8 은 soft delete (deleted_at NOT NULL)
--     - check_job · extraction_job 에 RUNNING·FAILED 행이 섞여 있다
--     - comment 3 은 comment 2 의 대댓글(parent_id)이고 재검토가 1회 걸려 있다
--     - EXISTING 후보는 occurrence_count 가 NULL 이다 (createExisting 규약)
--     - notification 은 읽음/안읽음이 섞여 있고 dedupe_key 로 멱등이 잡혀 있다
-- =============================================================================


